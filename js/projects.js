function getProjectOrderKey(project) {
  const match = project.coverImage.match(/\/([0-9]{2})_([^/]+)\//);
  if (!match) return "";
  // Las dos carpetas 41 corresponden a proyectos distintos.
  return match[1] === "41" ? `${match[1]}_${match[2]}` : match[1];
}

