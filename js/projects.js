function renderProjectsGallery() {
  const filterCont = document.getElementById("categories-filter");
  const gridCont = document.getElementById("proyectos-gallery-grid");

  if (!filterCont || !gridCont) return;

  const cats = [
    "TODOS",
    "OBRA NUEVA",
    "REFORMAS",
    "COMERCIAL",
    "OFICINAS",
    "OBRAS VARIAS",
    ONGOING_CATEGORY
  ];

  filterCont.innerHTML = cats.map(c => `
    <button
      type="button"
      data-cat="${c}"
      aria-pressed="${activeFilter === c}"
      aria-controls="proyectos-gallery-grid"
      class="project-filter py-1 transition-colors duration-150 ${
        activeFilter === c
          ? "text-black font-normal"
          : "text-neutral-400 hover:text-black"
      }"
    >
      <span>${c}</span>
    </button>
  `).join("");

  filterCont.querySelectorAll(".project-filter").forEach(btn => {
    btn.addEventListener("click", () => {
      activeFilter = btn.dataset.cat;
      renderProjectsGallery();
      Array.from(filterCont.querySelectorAll(".project-filter"))
        .find(candidate => candidate.dataset.cat === activeFilter)?.focus({ preventScroll: true });
    });
  });

  const showOngoingPhotos = activeFilter === ONGOING_CATEGORY;
  const filtered =
    activeFilter === "TODOS"
      ? ORDERED_PROJECTS_DATA
      : ORDERED_PROJECTS_DATA.filter(p => projectCategories(p).includes(activeFilter));

  gridCont.innerHTML = filtered.length
    ? filtered.map(p => projectCard(p, showOngoingPhotos)).join("")
    : '<p class="projects-empty" role="status">No hay proyectos disponibles en esta categoría.</p>';

  filtered.forEach(async (project, index) => {
    if (!project.photosFolder) return;
    const image = gridCont.children[index].querySelector("img, [data-project-photo]");
    const files = await loadProjectPhotos(project);
    const cover = await findProjectCover(project, files);
    if (cover && image?.isConnected) {
      if (image.tagName === "IMG") image.src = siteUrl(cover);
      else image.outerHTML = projectCardImage(project, cover);
    }
  });

  if (showOngoingPhotos) {
    filtered.forEach(async (project, index) => {
      if (!project.ongoingPhotos) return;
      const image = gridCont.children[index].querySelector("img");
      const photos = await loadOngoingPhotos(project);
      const cover = await checkOngoingPhoto(project, photos.portada);
      if (cover && image.isConnected) image.src = siteUrl(cover);
    });
  }
}

