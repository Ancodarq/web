// DETALLE DE PROYECTO
// Grilla editorial + lightbox
// ======================================================

let currentProjectImages = [];
let currentLightboxIndex = 0;

function renderProjectDetail() {
  const container = document.getElementById("project-detail-content");
  if (!container) return;

  const params = new URLSearchParams(window.location.search);
  const slug = params.get("slug");

  const project = PROJECTS_DATA.find(p => p.slug === slug);

  if (!project) {
    container.innerHTML =
      '<p class="text-sm text-neutral-500">Proyecto no encontrado.</p>';
    return;
  }

  currentProjectImages = [
    project.coverImage,
    ...(project.gallery || [])
  ];

  container.innerHTML = `
    <div class="mb-8 md:mb-10">
      <h1 class="text-[13px] md:text-[15px] font-light tracking-[0.18em] text-neutral-800 uppercase">
        ${project.name}
      </h1>

      <div class="mt-4 space-y-1 font-light">
        <p class="text-[13px] leading-relaxed text-neutral-600">
          ${project.description || "Mini descripción"}
        </p>
        <p class="text-[11px] tracking-[0.12em] text-neutral-400 uppercase">
          ${project.studioClient || "Estudio / cliente"}
        </p>
      </div>
    </div>

    <div class="project-gallery-grid">
      ${currentProjectImages.map((src, index) => `
        <button
          type="button"
          class="project-gallery-item"
          onclick="openProjectLightbox(${index})"
          aria-label="Abrir imagen ${index + 1} de ${project.name}"
        >
          <img
            src="${siteUrl(src)}"
            alt="${project.name} — imagen ${index + 1}"
            loading="${index < 3 ? 'eager' : 'lazy'}"
          />
        </button>
      `).join("")}
    </div>
  `;
}


// ======================================================
// LIGHTBOX
// ======================================================

function openProjectLightbox(index) {
  if (!currentProjectImages.length) return;

  currentLightboxIndex = index;

  const overlay = document.createElement("div");
  overlay.id = "project-lightbox";
  overlay.className = "project-lightbox";

  overlay.innerHTML = `
    <button
      class="project-lightbox-close"
      onclick="closeProjectLightbox()"
      aria-label="Cerrar"
    >
      ×
    </button>

    <button
      class="project-lightbox-arrow project-lightbox-arrow--left"
      onclick="event.stopPropagation(); changeProjectLightbox(-1)"
      aria-label="Imagen anterior"
    >
      ‹
    </button>

    <div class="project-lightbox-main">
      <img
        id="project-lightbox-image"
        src="${siteUrl(currentProjectImages[currentLightboxIndex])}"
        alt=""
      />
    </div>

    <button
      class="project-lightbox-arrow project-lightbox-arrow--right"
      onclick="event.stopPropagation(); changeProjectLightbox(1)"
      aria-label="Imagen siguiente"
    >
      ›
    </button>

    <div class="project-lightbox-thumbs">
      ${currentProjectImages.map((img, i) => `
        <button
          type="button"
          class="project-lightbox-thumb ${
            i === currentLightboxIndex ? "is-active" : ""
          }"
          onclick="event.stopPropagation(); setProjectLightboxImage(${i})"
          aria-label="Ver imagen ${i + 1}"
        >
          <img src="${siteUrl(img)}" alt="" />
        </button>
      `).join("")}
    </div>
  `;

  overlay.addEventListener("click", (event) => {
    if (event.target === overlay) {
      closeProjectLightbox();
    }
  });

  document.body.appendChild(overlay);
  document.body.style.overflow = "hidden";
}


function closeProjectLightbox() {
  const overlay = document.getElementById("project-lightbox");

  if (overlay) {
    overlay.remove();
  }

  document.body.style.overflow = "";
}


function changeProjectLightbox(direction) {
  if (!currentProjectImages.length) return;

  currentLightboxIndex =
    (currentLightboxIndex + direction + currentProjectImages.length)
    % currentProjectImages.length;

  updateProjectLightbox();
}


function setProjectLightboxImage(index) {
  currentLightboxIndex = index;
  updateProjectLightbox();
}


function updateProjectLightbox() {
  const image = document.getElementById("project-lightbox-image");

  if (image) {
    image.src = siteUrl(
      currentProjectImages[currentLightboxIndex]
    );
  }

  document
    .querySelectorAll(".project-lightbox-thumb")
    .forEach((thumb, index) => {
      thumb.classList.toggle(
        "is-active",
        index === currentLightboxIndex
      );
    });

  const activeThumb = document.querySelector(
    ".project-lightbox-thumb.is-active"
  );

  if (activeThumb) {
    activeThumb.scrollIntoView({
      behavior: "smooth",
      inline: "center",
      block: "nearest"
    });
  }
}


// ======================================================
// TECLADO: ESC / ← / →
// ======================================================

document.addEventListener("keydown", (event) => {
  const lightbox = document.getElementById("project-lightbox");

  if (!lightbox) return;

  if (event.key === "Escape") {
    closeProjectLightbox();
  }

  if (event.key === "ArrowLeft") {
    changeProjectLightbox(-1);
  }

  if (event.key === "ArrowRight") {
    changeProjectLightbox(1);
  }
});


// ======================================================
// INICIALIZACIÓN
// ======================================================

document.addEventListener("DOMContentLoaded", () => {
  renderHomeProjects();
  renderProjectsGallery();
  renderProjectDetail();
});
